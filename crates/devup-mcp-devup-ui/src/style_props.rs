//! Known `@devup-ui/react` primitive prop names, sourced verbatim from the
//! published Style Props API reference
//! (<https://github.com/dev-five-git/devup-ui/blob/main/apps/landing/src/app/(detail)/docs/api/style-props/page.mdx>),
//! not invented. `devup_ui_validate`'s `unknown-prop` rule checks JSX
//! attributes on the primitive elements it recognizes (`Box`, `Flex`,
//! `Text`, `Center`, `Grid`, `Image`) against this list plus a small set of
//! standard React/HTML/devup-ui-specific non-style props; anything else is
//! flagged rather than guessed at.
//!
//! `DEVUP_COLOR_LIKE_PROPS` / `DEVUP_LENGTH_LIKE_PROPS` are the subsets
//! whose CSS-property counterpart is a single color or length value; they
//! drive the `hardcoded-color` / `hardcoded-length` / `unknown-token`
//! rules. Deliberately conservative: composite props like `background`
//! (can hold a gradient) or `border` (shorthand for width+style+color) are
//! excluded from both subsets rather than guessed at, since flagging them
//! incorrectly would repeat exactly the fabrication failure this tool
//! exists to prevent.

/// devup-ui primitive components whose JSX props this validator checks
/// against [`DEVUP_STYLE_PROPS`] for the `unknown-prop` rule. Custom
/// component names are never flagged: unlike these primitives, a custom
/// component's valid prop set cannot be known statically from devup-ui's
/// public docs, so guessing which props it accepts would risk exactly the
/// kind of invented-fact failure this tool exists to prevent.
pub const DEVUP_PRIMITIVE_ELEMENTS: &[&str] = &["Box", "Flex", "Text", "Center", "Grid", "Image"];

