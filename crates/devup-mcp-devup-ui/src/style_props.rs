/// Returns true for props no primitive-specific check should ever flag:
/// standard React/HTML attributes, `on*` event handlers, `data-*`/`aria-*`,
/// and devup-ui pseudo-state / responsive-condition props (which are
/// user-defined selector keys, not a fixed enumerable set).
pub fn is_known_non_style_prop(name: &str) -> bool {
    DEVUP_NON_STYLE_PROPS.contains(&name)
        || name.starts_with("on")
        || name.starts_with("data-")
        || name.starts_with("aria-")
        || name.starts_with('_')
}

pub fn is_known_style_prop(name: &str) -> bool {
    DEVUP_STYLE_PROPS.binary_search(&name).is_ok()
}

pub fn is_color_like_prop(name: &str) -> bool {
    DEVUP_COLOR_LIKE_PROPS.binary_search(&name).is_ok()
}

pub fn is_length_like_prop(name: &str) -> bool {
    DEVUP_LENGTH_LIKE_PROPS.binary_search(&name).is_ok()
}

